// Build and check the native companion using Go alone.
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	hostcontract "browsefriend/shared"
)

func run(environment []string, args ...string) {
	cmd := exec.Command("go", args...)
	cmd.Env = append(os.Environ(), environment...)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func output(args ...string) string {
	cmd := exec.Command("go", args...)
	data, err := cmd.Output()
	if err != nil {
		panic(err)
	}
	return strings.TrimSpace(string(data))
}
func main() {
	root, err := os.Getwd()
	if err != nil {
		panic(err)
	}
	// go generate runs this command with shared as its working directory.
	if filepath.Base(root) == "shared" {
		root = filepath.Dir(root)
		if err = os.Chdir(root); err != nil {
			panic(err)
		}
	}
	args := strings.Join(os.Args[1:], " ")
	javascript := []byte("// Generated by go generate ./shared; edit host-contract.json.\nexport const HOST_CONTRACT = Object.freeze(" + strings.TrimSpace(string(hostcontract.Data)) + ");\n")
	path := filepath.Join(root, "shared", "host-contract.js")
	if strings.Contains(args, "--check") {
		data, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(data, javascript) {
			fmt.Fprintln(os.Stderr, "Shared browser contract is stale. Run go generate ./shared.")
			os.Exit(1)
		}
	} else {
		if err = os.WriteFile(path, javascript, 0644); err != nil {
			panic(err)
		}
	}
	if strings.Contains(args, "--generate-only") {
		return
	}
	if err = os.MkdirAll("build", 0755); err != nil {
		panic(err)
	}
	run([]string{"CGO_ENABLED=0"}, "build", "-trimpath", "-o", "build/browsefriend-native-host", "./native-host/cmd/browsefriend-native-host")
	run(nil, "build", "-o", "build/browsefriend-test-host", "./native-host/cmd/test-host")
	if strings.Contains(args, "--test") {
		run([]string{"BROWSEFRIEND_TEST_BINARY=" + filepath.Join(root, "build", "browsefriend-native-host")}, "test", "-race", "-coverprofile=build/go.cover", "./...")
		run(nil, "vet", "./...")
	}
	if strings.Contains(args, "--cross") {
		for _, platform := range []string{"darwin", "linux"} {
			for _, arch := range []string{"arm64", "amd64"} {
				run([]string{"CGO_ENABLED=0", "GOOS=" + platform, "GOARCH=" + arch}, "build", "-trimpath", "-o", "build/browsefriend-"+platform+"-"+arch, "./native-host/cmd/browsefriend-native-host")
			}
		}
	}
	var notices strings.Builder
	notices.WriteString("BrowseFriend native companion: third-party licenses\n")
	modules := strings.Split(output("list", "-deps", "-f", "{{if .Module}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}{{end}}", "./native-host/cmd/browsefriend-native-host"), "\n")
	modules = append(modules, "Go standard library|"+output("env", "GOVERSION")+"|"+output("env", "GOROOT"))
	seen := map[string]bool{}
	for _, line := range modules {
		parts := strings.Split(line, "|")
		if len(parts) != 3 || parts[0] == "browsefriend" || seen[line] {
			continue
		}
		seen[line] = true
		fmt.Fprintf(&notices, "\n%s %s\n", parts[0], parts[1])
		for _, file := range []string{"LICENSE", "NOTICE"} {
			data, err := os.ReadFile(filepath.Join(parts[2], file))
			if err != nil {
				if file == "NOTICE" && os.IsNotExist(err) {
					continue
				}
				panic(err)
			}
			notices.Write(data)
			notices.WriteByte('\n')
		}
	}
	if err = os.WriteFile("build/THIRD-PARTY-NOTICES.txt", []byte(notices.String()), 0644); err != nil {
		panic(err)
	}
}
