// Build and check the native companion using Go alone.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"

	hostcontract "browsefriend/shared"
)

func run(environment []string, command string, args ...string) {
	cmd := exec.Command(command, args...)
	cmd.Env = append(os.Environ(), environment...)
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func output(environment []string, args ...string) string {
	cmd := exec.Command("go", args...)
	cmd.Env = append(os.Environ(), environment...)
	data, err := cmd.Output()
	if err != nil {
		panic(err)
	}
	return strings.TrimSpace(string(data))
}
func suffix(platform string) string {
	if platform == "windows" {
		return ".exe"
	}
	return ""
}
func buildTarget(platform, arch string) {
	env := []string{"CGO_ENABLED=0", "GOOS=" + platform, "GOARCH=" + arch}
	prefix := "build/browsefriend-" + platform + "-" + arch
	run(env, "go", "build", "-trimpath", "-o", prefix+suffix(platform), "./native-host/cmd/browsefriend-native-host")
	if platform == "windows" {
		run(env, "go", "build", "-o", prefix+"-test-host.exe", "./native-host/cmd/test-host")
		run(env, "go", "test", "-c", "-o", prefix+"-companion.test.exe", "./native-host/internal/companion")
		run(env, "go", "test", "-c", "-o", prefix+"-command.test.exe", "./native-host/cmd/browsefriend-native-host")
	}
}
func main() {
	check := flag.Bool("check", false, "reject generated contract drift")
	generate := flag.Bool("generate-only", false, "generate the shared browser contract only")
	test := flag.Bool("test", false, "run local Go tests and vet")
	cross := flag.Bool("cross", false, "build all macOS/Linux/Windows ARM64/x64 targets and Windows tests")
	windowsTests := flag.Bool("windows-tests", false, "cross-compile Windows ARM64/x64 binaries and tests")
	install := flag.Bool("install", false, "install the local standalone binary")
	uninstall := flag.Bool("uninstall", false, "unregister the local standalone binary")
	flag.Parse()
	if flag.NArg() != 0 || (*install && *uninstall) {
		fmt.Fprintln(os.Stderr, "Use known flags; choose either install or uninstall.")
		os.Exit(1)
	}
	root, err := os.Getwd()
	if err != nil {
		panic(err)
	}
	if filepath.Base(root) == "shared" {
		root = filepath.Dir(root)
		if err = os.Chdir(root); err != nil {
			panic(err)
		}
	}
	javascript := []byte("// Generated by go generate ./shared; edit host-contract.json.\nexport const HOST_CONTRACT = Object.freeze(" + strings.TrimSpace(string(hostcontract.Data)) + ");\n")
	path := filepath.Join(root, "shared", "host-contract.js")
	if *check {
		data, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(data, javascript) {
			fmt.Fprintln(os.Stderr, "Shared browser contract is stale. Run go generate ./shared.")
			os.Exit(1)
		}
	} else if err = os.WriteFile(path, javascript, 0644); err != nil {
		panic(err)
	}
	if *generate {
		return
	}
	if err = os.MkdirAll("build", 0755); err != nil {
		panic(err)
	}
	host := filepath.Join(root, "build", "browsefriend-native-host"+suffix(runtime.GOOS))
	run([]string{"CGO_ENABLED=0"}, "go", "build", "-trimpath", "-o", host, "./native-host/cmd/browsefriend-native-host")
	run([]string{"CGO_ENABLED=0"}, "go", "build", "-o", "build/browsefriend-test-host"+suffix(runtime.GOOS), "./native-host/cmd/test-host")
	if *test {
		args := []string{"test", "-coverprofile=build/go.cover"}
		if runtime.GOOS == "windows" && runtime.GOARCH == "arm64" {
			fmt.Println("Windows ARM64: Go race detector unavailable; running ordinary tests.")
		} else {
			args = append(args, "-race")
		}
		args = append(args, "./...")
		run([]string{"BROWSEFRIEND_TEST_BINARY=" + host}, "go", args...)
		run(nil, "go", "vet", "./...")
	}
	if *cross || *windowsTests {
		platforms := []string{"windows"}
		if *cross {
			platforms = []string{"darwin", "linux", "windows"}
		}
		for _, platform := range platforms {
			for _, arch := range []string{"arm64", "amd64"} {
				buildTarget(platform, arch)
			}
		}
	}
	var notices strings.Builder
	notices.WriteString("BrowseFriend native companion: third-party licenses\n")
	modules := []string{}
	for _, platform := range []string{"darwin", "linux", "windows"} {
		env := []string{"GOOS=" + platform, "GOARCH=amd64", "CGO_ENABLED=0"}
		modules = append(modules, strings.Split(output(env, "list", "-deps", "-f", "{{if .Module}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}{{end}}", "./native-host/cmd/browsefriend-native-host"), "\n")...)
	}
	modules = append(modules, "Go standard library|"+output(nil, "env", "GOVERSION")+"|"+output(nil, "env", "GOROOT"))
	seen := map[string]bool{}
	for _, line := range modules {
		parts := strings.Split(line, "|")
		if len(parts) != 3 || parts[0] == "browsefriend" || seen[line] {
			continue
		}
		seen[line] = true
		fmt.Fprintf(&notices, "\n%s %s\n", parts[0], parts[1])
		for _, file := range []string{"LICENSE", "NOTICE"} {
			data, err := os.ReadFile(filepath.Join(parts[2], file))
			if err != nil {
				if file == "NOTICE" && os.IsNotExist(err) {
					continue
				}
				panic(err)
			}
			notices.Write(data)
			notices.WriteByte('\n')
		}
	}
	if err = os.WriteFile("build/THIRD-PARTY-NOTICES.txt", []byte(notices.String()), 0644); err != nil {
		panic(err)
	}
	if *install {
		run(nil, host, "install")
	}
	if *uninstall {
		run(nil, host, "uninstall")
	}
}
